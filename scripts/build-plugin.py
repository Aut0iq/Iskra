#!/usr/bin/env python3
"""Build the Iskra Zeron plugin staging tree.

Outputs (script-owned only):

  plugin/iskra/assets/          generated: animations.luau + the V6 frames
                                the source manifest references
  <output>/iskra-<version>/     UNSIGNED plugin staging folder with the
                                plugin's source manifest + code + the
                                generated assets + verbatim copies of
                                the repo-root license files (tests, temp
                                files, dotfiles and secrets excluded; a
                                stale "signature" field is stripped,
                                never faked)

Nothing here signs, installs or publishes: Zeron refuses unsigned plugin
folders, and only Zeron's own signing (the consent sheet's "It's mine…"
on a staged folder, or a signed MCP create/save flow) + `zeron plugin
export` produce a distributable .zeron-plugin. See docs/PLUGIN.md.

Usage:
    scripts/build-plugin.py [--source-manifest assets/v6/manifest.json]
                            [--output dist] [--repo-root <repo>]
                            [--wait SECONDS]
"""

import argparse
import json
import os
import shutil
import sys
import tempfile
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import lib_assets

REPO_ROOT = Path(__file__).resolve().parent.parent
PLUGIN_REL = Path("plugin/iskra")
ASSETS_REL = Path("assets")  # inside plugin/iskra
PLUGIN_FILES_REQUIRED = ("zeron-plugin.json", "init.luau", "zeron.luau")

# Repo-root release files copied verbatim into every staged artifact.
# They live only at the repo root — never duplicated into plugin/iskra.
ROOT_LICENSE_FILES = ("LICENSE", "LICENSE-ARTWORK", "ARTWORK.md", "TRADEMARKS.md")

# Never copied into the staged plugin folder.
EXCLUDE_DIRS = {"tests", "test", "tmp", "temp", "__pycache__", ".git"}
EXCLUDE_SUFFIXES = (".tmp", ".swp", ".key", ".pem", ".p12", ".pfx", ".env")
EXCLUDE_SUBSTRINGS = ("secret", "credential", "id_rsa", "id_ed25519", "id_dsa")


def _excluded(rel: Path) -> bool:
    for part in rel.parts:
        if part.startswith("."):
            return True
        if part.lower() in EXCLUDE_DIRS:
            return True
    name = rel.name.lower()
    if name.endswith(("~", ".bak")):
        return True
    if any(name.endswith(s) for s in EXCLUDE_SUFFIXES):
        return True
    if any(s in name for s in EXCLUDE_SUBSTRINGS):
        return True
    return False


def render_module(manifest: dict) -> str:
    """Deterministic Luau module: sorted keys, plugin-relative frame paths."""
    out = [
        "-- Generated by scripts/build-plugin.py from the V6 asset manifest.",
        "-- Do not edit by hand; regenerate with scripts/build-plugin.py.",
        "return {",
    ]
    for name in sorted(manifest["animations"]):
        entry = manifest["animations"][name]
        out.append(f"    {name} = {{")
        out.append("        frames = {")
        for rel in entry["frames"]:
            out.append(f'            "assets/v6/{rel}",')
        out.append("        },")
        out.append(f"        frame_ms = {entry['frame_ms']},")
        out.append("    },")
    out.append("}")
    out.append("")
    return "\n".join(out)


def _stamp() -> str:
    return time.strftime("%Y%m%dT%H%M%S") + f"-{os.getpid()}"


def _swap_into_place(new_dir: Path, dest: Path, owner_marker: str):
    """Replace dest with new_dir. dest must be absent or already
    script-owned (contains owner_marker); a pre-existing owned dest is
    moved aside to a unique dot-backup and NEVER deleted."""
    # Dot-prefixed backup name: preserved but excluded from plugin staging.
    old = dest.with_name(f".{dest.name}.bak-{_stamp()}")
    if dest.exists():
        if not (dest / owner_marker).exists():
            raise lib_assets.AssetError(
                f"refusing to replace {dest}: not generated by this script "
                f"(missing {owner_marker})"
            )
        dest.rename(old)
    try:
        new_dir.rename(dest)
    except Exception:
        if old.exists():
            old.rename(dest)
        raise
    if old.exists():
        print(f"previous generated folder preserved: {old}")


def generate_assets(repo_root: Path, source_manifest: Path, avatar=None) -> dict:
    """Validate the V6 manifest, then rebuild plugin/iskra/assets from a
    fresh temp tree. Fails before touching the final location."""
    plugin_dir = repo_root / PLUGIN_REL
    assets_dest = plugin_dir / ASSETS_REL
    src_root = source_manifest.parent

    manifest = lib_assets.load_manifest(source_manifest)
    rels = lib_assets.validate_frames(manifest, src_root)
    module_text = render_module(manifest)

    plugin_dir.mkdir(parents=True, exist_ok=True)
    tmp = Path(
        tempfile.mkdtemp(prefix=".assets.new-", dir=str(plugin_dir))
    )
    try:
        shutil.copy2(source_manifest, tmp / "manifest.json")
        # Keep frames under v6/ so 'assets/v6/<rel>' resolves under assets/.
        frames_root = tmp / "v6"
        frames_root.mkdir()
        for rel in rels:
            out = frames_root / rel
            out.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(lib_assets.resolve_frame(src_root, rel), out)
        (tmp / "animations.luau").write_text(module_text, encoding="utf-8", newline="\n")
        if avatar:
            (tmp / "avatar.json").write_text(json.dumps(avatar, indent=2) + "\n", encoding="utf-8", newline="\n")
            (tmp / "ARTWORK.md").write_text(
                "# Custom avatar artwork\n\nAuthor: " + avatar["author"] +
                "\n\nLicense: " + avatar["license"] + "\n\n" + avatar["attribution"] + "\n",
                encoding="utf-8", newline="\n",
            )
        # Marks the folder as script-owned so a rebuild may replace it.
        (tmp / "GENERATED").write_text(
            "generated by scripts/build-plugin.py\n", encoding="utf-8", newline="\n"
        )
        _swap_into_place(tmp, assets_dest, "GENERATED")
    except Exception:
        shutil.rmtree(tmp, ignore_errors=True)
        raise
    return manifest


def _allowed(rel: Path) -> bool:
    """Staging allowlist: known plugin file shapes only, never arbitrary
    extras. `assets/` is the generated, script-owned tree."""
    parts = rel.parts
    name = rel.name
    if len(parts) == 1:
        return (
            name in ("zeron-plugin.json", "icon.svg")
            or name.endswith(".luau")
            or name.endswith(".md")
        )
    if parts[0] == "locales":
        return len(parts) == 2 and name.endswith(".json")
    if parts[0] == "assets":
        return True
    return False


def _root_license_files(repo_root: Path) -> list:
    """The repo-root release files that ship verbatim in every artifact.
    Fail closed: each must exist as a regular file — a missing file or
    a symlink aborts before anything is staged."""
    out = []
    for name in ROOT_LICENSE_FILES:
        f = repo_root / name
        if f.is_symlink():
            raise lib_assets.AssetError(
                f"release file is a symlink: {f}"
            )
        if not f.is_file():
            raise lib_assets.AssetError(
                f"required release file missing or not regular: {f}"
            )
        out.append(f)
    return out


def stage_plugin(repo_root: Path, output_dir: Path) -> Path:
    """Copy plugin sources into <output>/iskra-<version>/: allowlisted
    regular files only — symlinks and special files abort the stage,
    unexpected files are skipped with a loud warning. The repo-root
    license files are copied in verbatim. The manifest's signature
    field is stripped: staging never carries (or fabricates) a
    signature. An existing output folder is preserved to a unique
    backup, never deleted."""
    plugin_dir = repo_root / PLUGIN_REL
    manifest_path = plugin_dir / "zeron-plugin.json"
    meta = json.loads(manifest_path.read_text(encoding="utf-8"))
    pid = meta.get("id")
    if pid != "iskra":
        raise lib_assets.AssetError(
            f"{manifest_path}: id {pid!r} != 'iskra'"
        )
    version = lib_assets.check_version(meta.get("version"))
    stage_dir = output_dir / f"{pid}-{version}"
    license_files = _root_license_files(repo_root)

    output_dir.mkdir(parents=True, exist_ok=True)
    tmp = Path(
        tempfile.mkdtemp(
            prefix=f".{pid}-{version}.new-", dir=str(output_dir)
        )
    )
    try:
        copied = 0
        skipped = []
        for root, dirs, files in os.walk(plugin_dir, followlinks=False):
            root = Path(root)
            rel_root = root.relative_to(plugin_dir)
            kept_dirs = []
            for d in sorted(dirs):
                rel = rel_root / d
                if (root / d).is_symlink():
                    raise lib_assets.AssetError(
                        f"symlinked directory in plugin: {root / d}"
                    )
                if not _excluded(rel):
                    kept_dirs.append(d)
            dirs[:] = kept_dirs
            for f in sorted(files):
                rel = rel_root / f
                src = root / f
                if _excluded(rel):
                    continue
                if src.is_symlink():
                    raise lib_assets.AssetError(
                        f"symlinked file in plugin: {src}"
                    )
                if not src.is_file():
                    raise lib_assets.AssetError(
                        f"non-regular file in plugin: {src}"
                    )
                if not _allowed(rel):
                    skipped.append(str(rel))
                    continue
                dst = tmp / rel
                dst.parent.mkdir(parents=True, exist_ok=True)
                if f == "zeron-plugin.json" and rel_root == Path("."):
                    m = json.loads(src.read_text(encoding="utf-8"))
                    if "signature" in m:
                        m.pop("signature")
                        print(
                            "note: stripped stale 'signature' from staged "
                            "zeron-plugin.json (staging is unsigned)"
                        )
                    dst.write_text(
                        json.dumps(m, indent=2, sort_keys=True) + "\n",
                        encoding="utf-8", newline="\n",
                    )
                else:
                    shutil.copy2(src, dst)
                copied += 1
        for src in license_files:
            shutil.copy2(src, tmp / src.name)
            copied += 1
        for s in skipped:
            print(f"warning: skipped unexpected file: {s}")
        if stage_dir.exists():
            backup = stage_dir.with_name(
                stage_dir.name + f".bak-{_stamp()}"
            )
            stage_dir.rename(backup)
            print(f"previous staged folder preserved: {backup}")
        tmp.rename(stage_dir)
    except Exception:
        shutil.rmtree(tmp, ignore_errors=True)
        raise
    print(f"staged {copied} files -> {stage_dir}")
    return stage_dir


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument(
        "--source-manifest",
        type=Path,
        default=None,
        help="V6 manifest (default <repo>/assets/v6/manifest.json)",
    )
    ap.add_argument(
        "--output",
        type=Path,
        default=None,
        help="staging parent dir (default <repo>/dist)",
    )
    ap.add_argument(
        "--repo-root",
        type=Path,
        default=REPO_ROOT,
        help="repository root (default: parent of this script's dir)",
    )
    ap.add_argument(
        "--wait",
        type=float,
        default=30,
        help="seconds to wait for plugin sources before failing (default 30)",
    )
    ap.add_argument("--avatar", type=Path, help="validated custom avatar pack; replaces artwork only")
    args = ap.parse_args(argv)

    repo_root = args.repo_root.resolve()
    source_manifest = (
        args.source_manifest.resolve()
        if args.source_manifest
        else repo_root / "assets/v6/manifest.json"
    )
    output_dir = args.output.resolve() if args.output else repo_root / "dist"
    plugin_dir = repo_root / PLUGIN_REL

    avatar = None
    if args.avatar:
        if args.source_manifest:
            ap.error("choose --avatar or --source-manifest")
        import avatars
        try:
            avatar, _ = avatars.validate(args.avatar)
        except (ValueError, OSError, json.JSONDecodeError, lib_assets.AssetError) as error:
            ap.error(str(error))
        source_manifest = args.avatar.resolve() / "manifest.json"

    # 1. Generated assets — owned by this script, always rebuilt.
    try:
        manifest = generate_assets(repo_root, source_manifest, avatar)
    except lib_assets.AssetError as e:
        print(f"error: {e}", file=sys.stderr)
        return 2
    n_frames = sum(len(e["frames"]) for e in manifest["animations"].values())
    print(
        f"generated {plugin_dir / 'assets'}: "
        f"{len(manifest['animations'])} animations, {n_frames} frames"
    )

    # 2. Stage the plugin folder once its sources exist (another worker may
    #    still be writing them).
    deadline = time.monotonic() + max(0.0, args.wait)
    while True:
        missing = [
            f for f in PLUGIN_FILES_REQUIRED
            if not (plugin_dir / f).is_file()
        ]
        if not missing:
            break
        if time.monotonic() >= deadline:
            print(
                "error: plugin sources not present after wait: "
                + ", ".join(str(plugin_dir / f) for f in missing)
                + "\nGenerated assets are in place; rerun once "
                "plugin/iskra sources land.",
                file=sys.stderr,
            )
            return 3
        time.sleep(1.0)

    try:
        stage_dir = stage_plugin(repo_root, output_dir)
    except (lib_assets.AssetError, json.JSONDecodeError) as e:
        print(f"error: {e}", file=sys.stderr)
        return 2

    print()
    print(f"UNSIGNED staging ready: {stage_dir}")
    print("It is not installable and holds no signature. To publish:")
    print("  1. review the staged tree, then stage it live:")
    print("       scripts/stage-plugin.sh --dist " + str(stage_dir))
    print("  2. sign with this device's key:  zeron plugin sign iskra")
    print("     (or the consent sheet's 'It's mine…' in Zeron — either way")
    print("     the 'commands' permission for zeron-pet is granted only")
    print("     by the person, in Zeron)")
    print("  3. export:  zeron plugin export iskra [--to <path>]")
    print("  4. attach the .zeron-plugin to a GitHub release; people install")
    print("     it from the release link or Settings -> Plugins -> Install…")
    print("See docs/PLUGIN.md for the full checklist.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
